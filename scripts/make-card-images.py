"""Makes small "-card" copies (640 px wide) of the article pictures used in blog cards.
Run again after new article pictures are added:  python3 scripts/make-card-images.py
Writes src/data/cardImages.ts (the list of pictures that have a card copy)."""
from PIL import Image
import glob, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
made = []
for f in sorted(glob.glob(f'{root}/public/assets/img/*.webp') + glob.glob(f'{root}/public/assets/wp/*.webp')):
    name = os.path.basename(f)
    if name.endswith('-card.webp') or re.search(r'-(80|120|400|600)\.webp$', name):
        continue
    im = Image.open(f)
    if im.width <= 640:
        continue
    h = round(im.height * 640 / im.width)
    out = f[:-5] + '-card.webp'
    im.convert('RGB').resize((640, h), Image.LANCZOS).save(out, 'WEBP', quality=78, method=6)
    made.append('/' + os.path.relpath(f, f'{root}/public'))
with open(f'{root}/src/data/cardImages.ts', 'w') as fh:
    fh.write('// Generated by scripts/make-card-images.py - pictures that have a small "-card" copy.\n')
    fh.write('export const CARD_IMAGES = new Set<string>([\n' + ''.join(f"  '{m}',\n" for m in made) + ']);\n')
print(len(made), 'card images')
